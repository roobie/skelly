// Regenerates the two vehicle index files from the files under deadvox's `vehicles` content folder. Jsonnet imports
// must be literal, so a vehicle's parts join the build only through a generated list; parallel vehicle authors each
// add their own files and never touch a shared one.
// Usage: node tools/vehicle-index.mjs [--hold id,id]
// `--hold` leaves out vehicles still being authored, so a landing need not wait for them.
import { mkdtempSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { parseArgs } from 'node:util';
import { compileJsonnetFile, REPOSITORY_ROOT } from './jsonnet/index.mjs';

const contentDir = join(REPOSITORY_ROOT, 'packages/deadvox/src/content/base/vehicles');
const thingDir = join(REPOSITORY_ROOT, 'packages/thing-authoring-tool/vehicles');
const INDEX = 'index.libsonnet';
const SHARED_ROWS = 'shared.libsonnet';
const { values } = parseArgs({ options: { hold: { type: 'string', default: '' } } });
const vehicleFiles = (dir) =>
  readdirSync(dir)
    .filter((file) => file.endsWith('.libsonnet') && file !== INDEX)
    .sort();
const contentFiles = vehicleFiles(contentDir);
const rowFileOf = (file) => (file === 'shared-parts.libsonnet' ? SHARED_ROWS : file);
const held = new Set(
  values.hold
    .split(',')
    .map((id) => id.trim())
    .filter(Boolean)
    .map((id) => `${id}.libsonnet`),
);
const load = (file) => {
  const data = JSON.parse(compileJsonnetFile(join(contentDir, file)));
  if (!Array.isArray(data.items)) {
    throw new Error(`${file} has no \`items\` list`);
  }
  return { file, ...data };
};
const thingFiles = new Set(vehicleFiles(thingDir));
// A vehicle in progress can have its row file before its content file, so either folder makes a held name real.
const unknownHeld = [...held].filter((file) => !(contentFiles.includes(file) || thingFiles.has(rowFileOf(file))));
if (unknownHeld.length > 0) {
  throw new Error(`--hold names no file in the vehicles folders: ${unknownHeld.join(', ')}`);
}
const files = contentFiles.filter((file) => !held.has(file));
const loaded = files.map(load);
const imports = (file) => `(import '${file}')`;
const rowImport = (file) => imports(`packages/thing-authoring-tool/vehicles/${file}`);
const itemIds = loaded.flatMap(({ items }) => items.map((item) => item.id));
const rowFiles = files.map(rowFileOf).filter((file) => thingFiles.has(file));
const rowIndex = rowFiles.map(rowImport).join('\n+ ');

// A held vehicle may be mid-authoring and not compile yet. A kept vehicle that imports it fails its own compile, so
// skipping its items here only loses this check's naming of a kept vehicle that reuses its parts by id.
const heldItems = new Map();
for (const file of held) {
  try {
    for (const item of load(file).items) {
      heldItems.set(item.id, file);
    }
  } catch (error) {
    console.error(`held ${file} does not compile, so its parts go unchecked: ${error.message.split('\n')[0]}`);
  }
}
const needsHeld = loaded.flatMap(({ file, blueprint }) =>
  (blueprint?.fittings ?? [])
    .filter((fitting) => heldItems.has(fitting.part))
    .map((fitting) => `${file} fits ${fitting.part} from held ${heldItems.get(fitting.part)}`),
);

// Spec files are measures, not rows; a kit is an object of functions, so only a real row file is an array.
const heldRowFiles = [...held].map(rowFileOf);
const strayCandidates = [...thingFiles].filter(
  (file) => !(file.endsWith('.spec.libsonnet') || rowFiles.includes(file) || heldRowFiles.includes(file)),
);
const evaluateRows = () => {
  const dir = mkdtempSync(join(tmpdir(), 'vehicle-index-'));
  const source = join(dir, 'check.jsonnet');
  writeFileSync(
    source,
    `{
  rows: ${rowIndex || '[]'},
  strays: [${strayCandidates.map((file) => `if std.isArray(${rowImport(file)}) then '${file}'`).join(', ')}],
}
`,
  );
  try {
    return JSON.parse(compileJsonnetFile(source));
  } finally {
    rmSync(dir, { recursive: true });
  }
};
const { rows, strays } = evaluateRows();
const rowIds = new Set(rows.map((row) => row.id));
const itemSet = new Set(itemIds);
const problems = [
  ...needsHeld,
  ...itemIds.filter((id) => !rowIds.has(id)).map((id) => `item ${id} has no row`),
  ...rows.filter((row) => !itemSet.has(row.id)).map((row) => `row ${row.id} has no item`),
  ...strays.filter(Boolean).map((file) => `row file ${file} has no content file, so nothing indexes it`),
];
if (problems.length > 0) {
  throw new Error(
    `vehicle index not written; hold what these need, or finish them:\n${[...new Set(problems)].join('\n')}`,
  );
}

writeFileSync(
  join(contentDir, INDEX),
  `// Generated by \`tools/vehicle-index.mjs\`.
{
  items: ${loaded.map(({ file }) => `${imports(file)}.items`).join('\n  + ')},
  blueprints: [
${loaded
  .filter(({ blueprint }) => blueprint)
  .map(({ file }) => `    ${imports(file)}.blueprint,`)
  .join('\n')}
  ],
  models: [
${itemIds.map((id) => `    import '../things/${id}.model.json',`).join('\n')}
  ],
}
`,
);
writeFileSync(
  join(thingDir, INDEX),
  // Root-relative, so `tools/model-look.mjs` can overlay this index with rows that have not landed.
  `// Generated by \`tools/vehicle-index.mjs\`.\n${rowIndex}\n`,
);
console.log(`${files.length} files, ${itemIds.length} parts`);
